"""R8: write reports/r8/RESULTS.md from the aggregated tables (every number comes from the files).

    python -m src.eval.report --out reports/r8/RESULTS.md

Reads reports/r8/main, reports/r8/small_three_modes, reports/r8/thresholds.json and
reports/r8/MANIFEST.json. Written text only states what the tables contain; interpretation lives in
docs/reports/r8_report_sections.md.
"""
import argparse
import json
import os

import pandas as pd

from src.eval.aggregate import fmt

MODE_ORDER = ["centralized", "independent", "full"]


def ci_cell(s: pd.DataFrame, mode: str, rate: float, metric: str) -> str:
    r = s[(s["mode"] == mode) & (s["rate"] == rate) & (s["metric"] == metric)]
    if r.empty:
        return "n/a"
    r = r.iloc[0]
    if pd.isna(r["ci_lo"]):
        return fmt(r["mean"])
    return f"{fmt(r['mean'])} [{fmt(r['ci_lo'])}, {fmt(r['ci_hi'])}]"


def table(summ: pd.DataFrame, rates, modes, metrics) -> str:
    head = ["λ/h", "mode", "n"] + [m for m, _ in metrics]
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for rate in rates:
        for mode in modes:
            n = summ[(summ["mode"] == mode) & (summ["rate"] == rate)]["n"]
            if n.empty:
                continue
            row = [f"{rate:g}", mode, str(int(n.max()))] + [ci_cell(summ, mode, rate, m) for _, m in metrics]
            lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="reports/r8")
    ap.add_argument("--out", default="reports/r8/RESULTS.md")
    args = ap.parse_args()
    man = json.load(open(os.path.join(args.dir, "MANIFEST.json"), encoding="utf-8"))
    main_s = pd.read_csv(os.path.join(args.dir, "main", "summary.csv"))
    small_s = pd.read_csv(os.path.join(args.dir, "small_three_modes", "summary.csv"))
    main_runs = pd.read_csv(os.path.join(args.dir, "main", "runs.csv"))
    small_runs = pd.read_csv(os.path.join(args.dir, "small_three_modes", "runs.csv"))
    crit = json.load(open(os.path.join(args.dir, "thresholds.json"), encoding="utf-8"))
    missing = {n: [x for x in open(os.path.join(args.dir, n, "missing.txt")).read().split() if x]
               for n in ("main", "small_three_modes")}

    groups = {}
    for c in crit:
        groups.setdefault(c["group"], []).append(c["pass"])

    L = ["# R8 results (generated)", "",
         "Generated by `python -m src.eval.report`. Do not edit by hand; rerun `python -m src.eval.run_all`.", "",
         "## What these numbers were produced from", "",
         f"- Code version: `{man['git_commit']}`; generated {man['generated']} on {man['platform']} "
         f"({man['cpu_count']} CPUs, Python {man['python']}).",
         f"- Travel times: **{man['traffic_model']}**.",
         f"- Predictor: {man['predictor']}.",
         f"- Main sweep: {len(main_runs)} finished runs ({len(missing['main'])} missing). "
         f"Three-mode sweep: {len(small_runs)} finished runs ({len(missing['small_three_modes'])} missing).",
         f"- Orders not accounted for (neither delivered nor failed): main {int(main_runs['unaccounted'].sum())}, "
         f"three-mode {int(small_runs['unaccounted'].sum())}.",
         "- Every cell is the mean over runs with a 95% bootstrap interval in brackets (10,000 resamples of "
         "the runs, seed 0). One run is one scenario file and one run seed.", ""]
    if missing["main"] or missing["small_three_modes"]:
        L += ["**Runs without a finished log (did not finish):** "
              + ", ".join(missing["main"] + missing["small_three_modes"]), ""]
    L += ["## Pre-registered criteria (docs/EXPERIMENT_PROTOCOL.md)", "",
          "| Criterion | Cells passed | Result |", "|---|---|---|"]
    for g, flags in groups.items():
        L.append(f"| {g} | {sum(flags)}/{len(flags)} | **{'PASS' if all(flags) else 'FAIL'}** |")
    L += ["", "Cell by cell: `reports/r8/thresholds.md`.", "",
          "## Ablation: independent against full (selective coordination off and on), main sweep", ""]
    rates = sorted(main_s["rate"].unique())
    L.append(table(main_s, rates, ["independent", "full"],
                   [("delivery time/order (s)", "delivery_time_mean_s"),
                    ("capacity violations", "violations_cap1"),
                    ("replans", "replans"), ("planning CPU (s)", "planning_cpu_s"),
                    ("messages", "messages_total")]))
    L += ["", "Paired differences (full - independent, matched by scenario file, seed and rate): "
          "`reports/r8/main/paired_full_vs_independent.csv`.", "",
          "## Three modes at λ = 10 per hour (small scenarios)", ""]
    L.append(table(small_s, sorted(small_s["rate"].unique()), MODE_ORDER,
                   [("delivery time/order (s)", "delivery_time_mean_s"),
                    ("capacity violations", "violations_cap1"),
                    ("planning CPU (s)", "planning_cpu_s"),
                    ("messages", "messages_total"),
                    ("on-time rate", "on_time_rate"), ("Jain", "jain")]))
    L += ["", "## Other metrics (main sweep, all rates pooled per mode)", ""]
    pooled = main_runs.groupby("mode")[["on_time_rate", "distance_km", "wait_s", "jain", "makespan_s",
                                        "failed"]].mean().reset_index()
    L.append("| mode | on-time rate | distance (km) | wait (s) | Jain | makespan (s) | failed orders |")
    L.append("|---|---|---|---|---|---|---|")
    for _, r in pooled.iterrows():
        cols = ["on_time_rate", "distance_km", "wait_s", "jain", "makespan_s", "failed"]
        L.append("| " + " | ".join([r["mode"]] + [fmt(r[c]) for c in cols]) + " |")
    L += ["", "## Figures", "",
          "- `reports/figures/F6_degradation_physical.png`", "- `reports/figures/F7_degradation_cost.png`",
          "- `reports/figures/F9_bars_operating_point.png`", ""]
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
