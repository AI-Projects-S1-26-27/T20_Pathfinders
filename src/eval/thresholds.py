"""R8 pre-registered success criteria (docs/EXPERIMENT_PROTOCOL.md, DECISIONS.md D12/D13).

    python -m src.eval.thresholds --main reports/r8/main --small reports/r8/small_three_modes \
        --out reports/r8/thresholds.md

The numbers below were fixed before the main sweeps were run; they are also written in
docs/EXPERIMENT_PROTOCOL.md. Do not change them after seeing main-sweep results. Each criterion is
evaluated exactly as written and reported as PASS / FAIL with the numbers behind it, a failed one
is reported as failed and analysed, never reworded.
"""
import argparse
import json
import os
from typing import Any, Dict, List

import pandas as pd

from src.eval.aggregate import paired

# ---- pre-registered values (H1, H2 from plan Section 7.3 of 29 Sep; H3 rates from the protocol) ----
H1_MAX_REL_DELIVERY_TIME = 0.10        # full within +10% of centralized (mean delivery time per order)
H2_MAX_RATIO = 0.50                    # full below half of centralized, planning CPU and messages
H3_RATES = (60.0, 150.0, 300.0)        # "medium and high" rates of the calibrated main sweep (0, 20, 60, 150, 300)
H3_METRICS = {"H3a": "delivery_time_mean_s", "H3b": "violations_cap1"}   # judged separately
SMALL_RATE = 10.0                      # the disruption rate at which the three modes are compared


def _row(pairs: pd.DataFrame, rate: float, metric: str) -> pd.Series:
    sel = pairs[(pairs["rate"] == rate) & (pairs["metric"] == metric)]
    if sel.empty:
        raise KeyError(f"no paired result for rate {rate:g}, metric {metric}")
    return sel.iloc[0]


def evaluate(main_dir: str, small_dir: str) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    small = pd.read_csv(os.path.join(small_dir, "runs.csv"))
    pc = paired(small, "full", "centralized", ["delivery_time_mean_s", "planning_cpu_s", "messages_total"])
    r = _row(pc, SMALL_RATE, "delivery_time_mean_s")
    out.append({"id": "H1", "group": "H1", "claim": f"full within +{H1_MAX_REL_DELIVERY_TIME:.0%} of centralized "
                f"delivery time at λ={SMALL_RATE:g}",
                "value": r["rel_mean"], "ci": [r["rel_lo"], r["rel_hi"]], "n_pairs": int(r["n_pairs"]),
                "pass": bool(r["rel_mean"] <= H1_MAX_REL_DELIVERY_TIME)})
    for metric, tag in (("planning_cpu_s", "H2a"), ("messages_total", "H2b")):
        r = _row(pc, SMALL_RATE, metric)
        ratio = 1.0 + r["rel_mean"]
        out.append({"id": tag, "group": tag, "claim": f"full uses at most {H2_MAX_RATIO:.0%} of centralized "
                    f"{metric} at λ={SMALL_RATE:g}",
                    "value": ratio, "ci": [1.0 + r["rel_lo"], 1.0 + r["rel_hi"]],
                    "n_pairs": int(r["n_pairs"]), "pass": bool(ratio <= H2_MAX_RATIO)})
    mainr = pd.read_csv(os.path.join(main_dir, "runs.csv"))
    pm = paired(mainr, "full", "independent", list(H3_METRICS.values()))
    for tag, metric in H3_METRICS.items():
        for rate in H3_RATES:
            r = _row(pm, rate, metric)
            better = bool((r["a_mean"] < r["b_mean"]) and not r["unpaired_ci_overlap"])
            out.append({"id": f"{tag} λ={rate:g}", "group": tag,
                        "claim": f"full lower than independent in {metric}, non-overlapping 95% CIs",
                        "value": r["diff_mean"], "ci": [r["diff_lo"], r["diff_hi"]],
                        "n_pairs": int(r["n_pairs"]), "pass": better,
                        "paired_ci_below_zero": bool(r["diff_hi"] < 0)})
    return out


def to_markdown(results: List[Dict[str, Any]]) -> str:
    groups: Dict[str, List[bool]] = {}
    for r in results:
        groups.setdefault(r["group"], []).append(r["pass"])
    lines = ["# Pre-registered criteria: outcome", "",
             "Generated by `python -m src.eval.thresholds`. Criteria are in docs/EXPERIMENT_PROTOCOL.md.", "",
             "## Roll-up (a criterion holds only if every cell of it passes)", "",
             "| Criterion | Cells passed | Result |", "|---|---|---|"]
    for g, flags in groups.items():
        lines.append(f"| {g} | {sum(flags)}/{len(flags)} | **{'PASS' if all(flags) else 'FAIL'}** |")
    lines += ["", "## Cells", "",
              "| Cell | Claim | Value | 95% CI | Pairs | Result |", "|---|---|---|---|---|---|"]
    for r in results:
        lo, hi = r["ci"]
        lines.append(f"| {r['id']} | {r['claim']} | {r['value']:.4g} | [{lo:.4g}, {hi:.4g}] | "
                     f"{r['n_pairs']} | **{'PASS' if r['pass'] else 'FAIL'}** |")
    lines += ["", "H1 value is the mean of (full / centralized - 1) over matched runs. H2 value is the mean of "
              "full / centralized. H3 value is the mean paired difference (full - independent) and the "
              "result uses the plan's rule: full is lower and the unpaired 95% CIs do not overlap; the "
              "last column of the JSON file also gives whether the paired CI lies below zero."]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Evaluate the pre-registered criteria.")
    ap.add_argument("--main", required=True)
    ap.add_argument("--small", required=True)
    ap.add_argument("--out", default="reports/r8/thresholds.md")
    args = ap.parse_args()
    results = evaluate(args.main, args.small)
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(to_markdown(results))
    with open(os.path.splitext(args.out)[0] + ".json", "w", encoding="utf-8") as f:
        json.dump(results, f, indent=1)
    for r in results:
        print(("PASS" if r["pass"] else "FAIL"), r["id"], round(r["value"], 4))


if __name__ == "__main__":
    main()
