"""
R3 · Week 7: statistics of the generated orders in the committed scenarios, next to the Amazon
profile they were sampled from (the "generated matches empirical" check, for the report's Data
section).

    python -m src.data.scenario_stats                 # writes reports/scenario_stats.md and .json

Generated columns come from configs/scenarios/*.yaml (committed, so anyone can rerun them). The
Amazon column needs the local profile (data/profile/summary.json and packages.csv, from
docs/data_profile.md steps 1-3; not committed, CC BY-NC data); without it that column says
"no profile".
"""

from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path

import numpy as np
import yaml

from src.kr.ontology import NO_TW_END, NO_TW_START, SIM_START_S

Q = (5, 25, 50, 75, 95)
QKEYS = ("0.05", "0.25", "0.5", "0.75", "0.95")
ASSUMED = {"priority": {1: 0.2, 2: 0.5, 3: 0.3}, "released_during_run": 0.3}


def _q(values) -> dict:
    if not len(values):
        return {}
    a = np.asarray(values, dtype=float)
    out = {k: float(np.percentile(a, p)) for k, p in zip(QKEYS, Q)}
    out["mean"] = float(a.mean())
    return out


def generated(config_glob: str) -> dict:
    files = sorted(glob.glob(config_glob))
    service, width, demand, n, n_tw, released, unservable = [], [], [], 0, 0, 0, 0
    prio = {1: 0, 2: 0, 3: 0}
    sources = set()
    for p in files:
        cfg = yaml.safe_load(Path(p).read_text(encoding="utf-8"))
        meta = cfg.get("scenario_meta") or {}
        sources.add(meta.get("demand_source", "?"))
        unservable += len(meta.get("orders_unservable_alone") or [])
        for o in cfg["orders"]:
            n += 1
            service.append(o["service_time"])
            demand.append(o["demand"])
            prio[int(o.get("priority", 2))] = prio.get(int(o.get("priority", 2)), 0) + 1
            released += o.get("release_time", SIM_START_S) > SIM_START_S
            if (o["tw_start"], o["tw_end"]) != (NO_TW_START, NO_TW_END):
                n_tw += 1
                width.append((o["tw_end"] - o["tw_start"]) / 3600.0)
    return {
        "files": len(files),
        "orders": n,
        "demand_sources": sorted(sources),
        "share_with_tw": n_tw / n if n else 0.0,
        "tw_width_h": _q(width),
        "service_time_s": _q(service),
        "demand_units": _q(demand),
        "priority_share": {k: v / n for k, v in sorted(prio.items())} if n else {},
        "released_during_run": released / n if n else 0.0,
        "orders_unservable_alone": unservable,
    }


def amazon(profile_dir: Path):
    """The profile's values for the same statistics, or None without a local profile."""
    summary = profile_dir / "summary.json"
    if not summary.exists():
        return None
    s = json.loads(summary.read_text(encoding="utf-8"))
    per_stop = True
    packages = profile_dir / "packages.csv"
    if packages.exists():
        import pandas as pd

        from src.data.orders_from_amazon import service_is_per_stop

        cols = ["route_id", "stop_id", "service_s"]
        per_stop = service_is_per_stop(pd.read_csv(packages, usecols=cols))
    key = "service_time_per_stop_s(max)" if per_stop else "service_time_per_stop_s(sum)"
    return {
        "routes": s.get("n_routes"),
        "share_with_tw": s.get("share_stops_with_any_tw"),
        "tw_width_h": s.get("tw_width_h", {}),
        "service_time_s": s.get(key, {}),
        "service_column": key,
    }


def _cells(q: dict, dec: int) -> str:
    if not q:
        return " | ".join(["-"] * 6)
    return " | ".join(f"{q[k]:,.{dec}f}" for k in QKEYS + ("mean",))


def report(gen: dict, amz) -> str:
    no = "no profile" if amz is None else None
    out = [
        "# Generated orders vs the Amazon profile",
        "",
        f"Generated by `python -m src.data.scenario_stats`; do not edit by hand. Generated: "
        f"{gen['orders']:,} orders in {gen['files']} files of `configs/scenarios/` "
        f"(demand source: {'; '.join(gen['demand_sources'])}). Amazon: "
        + ("no local profile (`data/profile/summary.json`), column left empty."
           if amz is None else f"{amz['routes']:,} routes, `data/profile/summary.json`."),
        "",
        "| Statistic | Source | p5 | p25 | median | p75 | p95 | mean |",
        "|---|---|---|---|---|---|---|---|",
        f"| Service time per stop (s) | generated | {_cells(gen['service_time_s'], 1)} |",
        f"| | Amazon ({no or amz['service_column']}) | "
        f"{_cells({} if amz is None else amz['service_time_s'], 1)} |",
        f"| Time-window width (h) | generated | {_cells(gen['tw_width_h'], 2)} |",
        f"| | Amazon ({no or 'tw_width_h'}) | "
        f"{_cells({} if amz is None else amz['tw_width_h'], 2)} |",
        f"| Demand (capacity units) | generated | {_cells(gen['demand_units'], 1)} |",
        "",
        "| Share | Generated | Amazon or assumption |",
        "|---|---|---|",
        f"| Orders with a time window | {100 * gen['share_with_tw']:.1f}% | "
        + ("no profile" if amz is None else f"{100 * amz['share_with_tw']:.1f}% of stops (Amazon)")
        + " |",
    ]
    for k, v in gen["priority_share"].items():
        out.append(f"| Priority {k} | {100 * v:.1f}% | {100 * ASSUMED['priority'][k]:.0f}% "
                   "(assumption, not in the data) |")
    out += [
        f"| Released during the run | {100 * gen['released_during_run']:.1f}% | "
        f"about {100 * ASSUMED['released_during_run']:.0f}% (assumption) |",
        f"| Orders no vehicle could serve alone | {gen['orders_unservable_alone']} | 0 (target) |",
        "",
        "Window widths are clipped to the 4-hour simulated period (06:00-10:00), so the generated "
        "widths cannot exceed 4 h while Amazon's median is about 8 h. Demand is packages x sampled "
        "volume in units of the median package volume (`scenario_meta.unit_cm3`), so it has no "
        "Amazon column.",
    ]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--configs", default="configs/scenarios/*.yaml")
    ap.add_argument("--profile-dir", default="data/profile")
    ap.add_argument("--md", default="reports/scenario_stats.md")
    ap.add_argument("--json", default="reports/scenario_stats.json")
    a = ap.parse_args(argv)
    gen, amz = generated(a.configs), amazon(Path(a.profile_dir))
    text = report(gen, amz)
    body = json.dumps({"generated": gen, "amazon": amz}, indent=1) + "\n"
    for path, content in ((a.md, text), (a.json, body)):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
